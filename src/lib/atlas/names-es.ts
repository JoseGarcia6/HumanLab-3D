export function normalizedTerm(value:string):string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLocaleLowerCase('es').trim();
}

const compiled=PHRASES.map(([from,to])=>({
  regex:new RegExp('\\b'+from.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'\\b','gi'),
  to,
}));

export function anatomicalNameEs(name:string):string {
  if(!name)return '';
  const original=name.trim(),exact=EXACT[original.toLowerCase()];
  if(exact)return exact;
  const side=/^(left|right)\s+/i.exec(original);
  let body=side?original.slice(side[0].length):original;
  body=body.toLowerCase();
  for(const term of compiled)body=body.replace(term.regex,term.to);
  body=body.replace(/\s+/g,' ').trim();
  if(!body)return original;
  const translated=body.charAt(0).toLocaleUpperCase('es')+body.slice(1);
  return side?translated+' (lado '+(side[1].toLowerCase()==='left'?'izquierdo':'derecho')+')':translated;
}

